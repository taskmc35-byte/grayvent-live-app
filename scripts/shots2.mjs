import { chromium } from 'playwright';
const out = process.argv[2];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell' });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: 'dark' });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto('http://localhost:4173/'); await p.waitForTimeout(600);
await p.getByText('Pannello staff').click(); await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/s1-list.png` });
await p.getByText('Aisha della Tribù').click(); await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/s2-editor.png`, fullPage: true });
await p.getByRole('button', { name: 'Salva scheda' }).click(); await p.waitForTimeout(400);
await p.getByRole('button', { name: 'Nuova scheda' }).click(); await p.waitForTimeout(300);
await p.locator('#nome').fill('Leonard'); await p.locator('#cognome').fill('da Skorstain');
await p.locator('#razza').selectOption('mezzelfo'); await p.locator('#ered').selectOption('alf');
await p.locator('label.chk', { hasText: /^Sviluppo Fisico 1$/ }).click();
await p.getByRole('button', { name: 'Salva scheda' }).click(); await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/s3-afterSave.png` });
await p.getByRole('button', { name: 'Abilità' }).click(); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Nuova abilità' }).click(); await p.waitForTimeout(300);
await p.locator('#ab-nome').fill('Sviluppo Fisico 2'); await p.locator('#ab-pf').fill('1'); await p.locator('#ab-tda').fill('3');
await p.screenshot({ path: `${out}/s4-ability.png` });
await p.getByRole('button', { name: 'Salva', exact: true }).click(); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Account' }).click(); await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/s5-account.png`, fullPage: true });
console.log(errs);
await b.close();

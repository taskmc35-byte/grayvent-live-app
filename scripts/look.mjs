const w = (ms = 400) => p.waitForTimeout(ms);
await p.goto('http://localhost:4173/'); await p.evaluate(() => localStorage.clear()); await p.reload(); await w(1200);
await p.screenshot({ path: `${OUT}/l1-login.png` });
await p.getByText('Sigurd Vreitsson').click(); await w();

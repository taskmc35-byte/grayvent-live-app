import { chromium } from 'playwright';
const out = process.argv[2];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell' });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: process.argv[3] || 'dark' });
const p = await ctx.newPage();
const errs = []; p.on('console', m => m.type() === 'error' && errs.push(m.text())); p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:4173/'); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/1-login.png` });
await p.getByText('Sigurd Vreitsson').click(); await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/2-scheda.png`, fullPage: true });
await p.locator('.zone').first().click(); await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/3-equip.png` });
await p.getByRole('button', { name: 'Salva' }).click(); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Abilità' }).click(); await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/4-abilita.png`, fullPage: true });
await p.getByRole('button', { name: 'Cambia personaggio' }).click(); await p.waitForTimeout(300);
await p.getByText('Lea Wings').click(); await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/5-lea.png`, fullPage: true });
await p.getByRole('button', { name: 'Poteri' }).click(); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Dardo Arcano' }).click(); await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/6-spell.png` });
await p.keyboard.press('Escape');
await p.getByRole('button', { name: 'Manuali' }).click(); await p.waitForTimeout(300);
await p.getByText('Manuale dei Misteri').click(); await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/7-pdf.png` });
console.log('errors:', errs);
await b.close();
